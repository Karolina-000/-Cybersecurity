# პირველი ხაზიდან ვიღებთ ორ რიცხვს: n (მონაწილეთა რაოდენობა) და k (k-ური ადგილი)
# split() ყოფს სტრიქონს space-ებზე, map(int, ...) კი თითოეულს რიცხვად აქცევს
n, k = map(int, input().split())

# მეორე ხაზიდან ვიღებთ n რიცხვს — ეს არის თითოეული მონაწილის ქულა
# scores[0] იქნება 1-ლი ადგილის ქულა, scores[1] მე-2 ადგილის და ა.შ.
scores = list(map(int, input().split()))


def count_qualified(scores, n, k):
    # ვქმნით ცვლადს, სადაც დავითვლით რამდენი მონაწილე გავა შემდეგ რაუნდში
    count = 0

    # k-ური ადგილის ქულა — ეს არის ზღვარი (threshold)
    # scores[k-1]-ს ვწერთ, რადგან სია ინდექსირდება 0-დან
    # მაგალითად, თუ k=3, გვინდა მე-3 მონაწილის ქულა, რომელიც არის scores[2]
    threshold = scores[k - 1]

    # ციკლით გავივლით ყველა მონაწილის ქულას
    for i in range(n):
        
        # პირობა: მონაწილე გადის შემდეგ რაუნდში თუ:
        # 1) მისი ქულა >= threshold (ანუ k-ური ადგილის ქულაზე მეტი ან ტოლი)
        # 2) მისი ქულა > 0 (დადებითი ქულა, წესის მიხედვით)
        if scores[i] >= threshold and scores[i] > 0:
            count += 1   # თუ პირობა სრულდება, ვამატებთ ერთ მონაწილეს
    
    # ვაბრუნებთ საბოლოო რაოდენობას
    return count


# ვიძახებთ ფუნქციას და ვინახავთ შედეგს
result = count_qualified(scores, n, k)

print(result)