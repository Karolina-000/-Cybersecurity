


# ვიღებთ მომხმარებლისგან სტრიქონს, ვყოფთ space-ებზე (split())
# და თითოეულ ელემენტს ვაქცევთ integer-ად (map(int, ...))
# შედეგად ვღებულობთ რიცხვების სიას (list)
# მაგალითად, თუ შეიყვანავ: 1 2 3 4 45 6 7 8 18
# numbers გახდება: [1, 2, 3, 4, 45, 6, 7, 8, 18]
#numbers = list(map(int, input().split()))



numbers = [1,2,3,4,45,6,7,28,18]


# ვქმნით ორ ცვლადს, სადაც შევინახავთ ჯამებს
# თავიდან ორივე ნულის ტოლია, რადგან ჯერ არაფერი არ დაგვითვლია
even_sum = 0   # ლუწი რიცხვების ჯამი
odd_sum = 0    # კენტი რიცხვების ჯამი

# ციკლით გავივლით სიის ყველა რიცხვს, ერთი-ერთზე
for number in numbers:
    
    # ვამოწმებთ, არის თუ არა number ლუწი
    # % არის ნაშთის ოპერატორი (modulo) — გვიბრუნებს გაყოფის ნაშთს
    # თუ number-ის 2-ზე გაყოფის ნაშთი 0-ის ტოლია, ესეიგი ლუწია
    if number % 2 == 0:
        # თუ ლუწია, ვამატებთ even_sum-ს
        even_sum += number   # ეს იგივეა რაც: even_sum = even_sum + number
    else:
        # თუარა (ანუ ნაშთი 1-ია), ესეიგი კენტია
        odd_sum += number    # ვამატებთ odd_sum-ს

# ციკლის დასრულების შემდეგ ვადარებთ ორ ჯამს ერთმანეთს
if even_sum > odd_sum:
    # თუ ლუწების ჯამი მეტია კენტების ჯამზე
    print("EVEN")
elif odd_sum > even_sum:
    # თუ კენტების ჯამი მეტია ლუწების ჯამზე
    print("ODD")
else:
    # თუ არცერთი პირობა არ შესრულდა, ესეიგი ჯამები ტოლია
    print("EQUAL")